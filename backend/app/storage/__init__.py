"""Evidence and derived-data object storage.

Object keys are always generated by the platform::

    tenants/<tenant_id>/captures/<capture_id>/original.<pcap|pcapng>   (evidence, write-once)
    tenants/<tenant_id>/captures/<capture_id>/derived/packets.parquet  (derived, replaceable)
    tenants/<tenant_id>/reports/<report_id>.<ext>

The tenant prefix is the storage boundary: every accessor builds keys through
``tenant_key`` so one tenant's objects can never be addressed from another
tenant's context. User-supplied filenames are kept only as metadata.
"""

from __future__ import annotations

import functools
import re
import shutil
from abc import ABC, abstractmethod
from pathlib import Path
from typing import BinaryIO

from app.core.config import get_settings

_SAFE = re.compile(r"^[A-Za-z0-9_.-]+$")


def _check_segment(seg: str) -> str:
    if not seg or seg in (".", "..") or not _SAFE.match(seg):
        raise ValueError(f"unsafe storage key segment: {seg!r}")
    return seg


def tenant_key(tenant_id: str, *parts: str) -> str:
    return "/".join(["tenants", _check_segment(tenant_id), *(_check_segment(p) for p in parts)])


class Storage(ABC):
    @abstractmethod
    def put_file(self, key: str, src: Path, content_type: str = "application/octet-stream") -> None: ...

    @abstractmethod
    def get_to_file(self, key: str, dest: Path) -> None: ...

    @abstractmethod
    def local_path(self, key: str) -> Path | None:
        """A directly readable local path if the backend has one (local backend), else None."""

    @abstractmethod
    def open_read(self, key: str) -> BinaryIO: ...

    @abstractmethod
    def delete_prefix(self, prefix: str) -> int: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    @abstractmethod
    def size(self, key: str) -> int: ...

    def materialize(self, key: str, cache_dir: Path) -> Path:
        """Return a local path for the object, downloading into the cache if needed."""
        lp = self.local_path(key)
        if lp is not None:
            return lp
        dest = cache_dir / key
        if not dest.exists():
            dest.parent.mkdir(parents=True, exist_ok=True)
            tmp = dest.with_suffix(dest.suffix + ".part")
            self.get_to_file(key, tmp)
            tmp.rename(dest)
        return dest


class LocalStorage(Storage):
    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        p = (self.root / key).resolve()
        if not p.is_relative_to(self.root):
            raise ValueError("storage key escapes the storage root")
        return p

    def put_file(self, key: str, src: Path, content_type: str = "application/octet-stream") -> None:
        dest = self._path(key)
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = dest.with_suffix(dest.suffix + ".part")
        shutil.copyfile(src, tmp)
        tmp.replace(dest)

    def get_to_file(self, key: str, dest: Path) -> None:
        shutil.copyfile(self._path(key), dest)

    def local_path(self, key: str) -> Path | None:
        return self._path(key)

    def open_read(self, key: str) -> BinaryIO:
        return self._path(key).open("rb")

    def delete_prefix(self, prefix: str) -> int:
        p = self._path(prefix)
        if p.is_dir():
            n = sum(1 for _ in p.rglob("*") if _.is_file())
            shutil.rmtree(p)
            return n
        if p.is_file():
            p.unlink()
            return 1
        return 0

    def exists(self, key: str) -> bool:
        return self._path(key).exists()

    def size(self, key: str) -> int:
        return self._path(key).stat().st_size


class S3Storage(Storage):
    def __init__(self):
        import boto3

        s = get_settings()
        self.bucket = s.s3_bucket
        self.sse = s.s3_server_side_encryption
        # Compose passes unset variables as empty strings; treat them as unset so AWS endpoints
        # and instance-role credentials are used.
        self.client = boto3.client(
            "s3",
            endpoint_url=s.s3_endpoint_url or None,
            region_name=s.s3_region,
            aws_access_key_id=s.s3_access_key or None,
            aws_secret_access_key=s.s3_secret_key or None,
        )

    def ensure_bucket(self) -> None:
        try:
            self.client.head_bucket(Bucket=self.bucket)
        except Exception:  # noqa: BLE001 - botocore raises ClientError subclasses
            self.client.create_bucket(Bucket=self.bucket)

    def _extra(self, content_type: str) -> dict:
        extra = {"ContentType": content_type}
        if self.sse:
            extra["ServerSideEncryption"] = self.sse
        return extra

    def put_file(self, key: str, src: Path, content_type: str = "application/octet-stream") -> None:
        self.client.upload_file(str(src), self.bucket, key, ExtraArgs=self._extra(content_type))

    def get_to_file(self, key: str, dest: Path) -> None:
        self.client.download_file(self.bucket, key, str(dest))

    def local_path(self, key: str) -> Path | None:
        return None

    def open_read(self, key: str) -> BinaryIO:
        return self.client.get_object(Bucket=self.bucket, Key=key)["Body"]

    def delete_prefix(self, prefix: str) -> int:
        n = 0
        paginator = self.client.get_paginator("list_objects_v2")
        for page in paginator.paginate(Bucket=self.bucket, Prefix=prefix):
            objs = [{"Key": o["Key"]} for o in page.get("Contents", [])]
            if objs:
                self.client.delete_objects(Bucket=self.bucket, Delete={"Objects": objs})
                n += len(objs)
        return n

    def exists(self, key: str) -> bool:
        try:
            self.client.head_object(Bucket=self.bucket, Key=key)
            return True
        except Exception:  # noqa: BLE001
            return False

    def size(self, key: str) -> int:
        return int(self.client.head_object(Bucket=self.bucket, Key=key)["ContentLength"])


@functools.lru_cache(maxsize=1)
def get_storage() -> Storage:
    s = get_settings()
    if s.storage_backend == "s3":
        st = S3Storage()
        st.ensure_bucket()
        return st
    return LocalStorage(s.storage_local_root)
