"""Regenerate the reference docs that are derived from code: docs/rules.md, docs/console.md, docs/missions.md.

    python -m scripts.gen_docs        (from backend/)

CI runs this and fails if the committed docs differ, so the references cannot drift from the code.
"""

from __future__ import annotations

import pathlib
import sys

from app.analysis.rules import rule_catalog
from app.console.engine import REGISTRY
from app.services.missions import MISSIONS

DOCS = pathlib.Path(__file__).resolve().parents[2] / "docs"
HEADER = "<!-- Generated by backend/scripts/gen_docs.py. Do not edit by hand. -->\n\n"


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {i}" for i in items) or "- none"


def rules_md() -> str:
    cats = rule_catalog()
    out = [HEADER, "# Detection rule catalogue\n\n",
           "Every finding is produced by one of these deterministic, versioned rules. Severity describes impact; confidence "
           "describes how directly the packets prove the conclusion. The two are rated separately.\n\n",
           "| Rule | Version | Category | Default severity | Title |\n|---|---|---|---|---|\n"]
    out += [f"| {r.rule_id} | {r.version} | {r.category} | {r.default_severity} | {r.title} |\n" for r in cats]
    for r in cats:
        out.append(f"\n## {r.rule_id}: {r.title}\n\n")
        out.append(f"**Version** {r.version} · **Category** {r.category} · **Default severity** {r.default_severity}\n\n")
        out.append(f"**Detection logic.** {r.detection_logic}\n\n**Severity rationale.** {r.severity_rationale}\n\n")
        out.append(f"**Required evidence**\n\n{_bullets(r.required_evidence)}\n\n**Limitations**\n\n{_bullets(r.limitations)}\n\n")
        out.append(f"**Known false positives**\n\n{_bullets(r.false_positives)}\n")
    return "".join(out)


def console_md() -> str:
    cmds = sorted(REGISTRY.commands.values(), key=lambda c: (c.category, c.name))
    out = [HEADER, "# Command Deck reference\n\n",
           "Commands run server-side against stored evidence and are checked against the caller's permissions. "
           "Missing arguments are prompted for interactively; `cancel` aborts a prompt. Tab completion is context-aware.\n"]
    cat = None
    for c in cmds:
        if c.category != cat:
            cat = c.category
            out.append(f"\n## {cat}\n\n| Command | Summary | Permission |\n|---|---|---|\n")
        out.append(f"| `{c.usage()}` | {c.summary} | `{c.permission}` |\n")
    return "".join(out)


def missions_md() -> str:
    out = [HEADER, "# Training missions\n\n",
           "Missions run on synthetic captures that ship in `backend/fixtures/training/`. They are labelled SYNTHETIC "
           "everywhere they appear and are excluded from production statistics. Answers are checked against the analysed "
           "capture (finding subjects, metrics and frames), not against stored strings.\n\n",
           "| Mission | Difficulty | XP | Captures | Objectives |\n|---|---|---|---|---|\n"]
    for mid, m in MISSIONS.items():
        out.append(f"| `{mid}` {m['title']} | {m['difficulty']} | {m['xp']} | {', '.join(m['files'])} | {len(m['objectives'])} |\n")
    for mid, m in MISSIONS.items():
        out.append(f"\n## {m['title']} (`{mid}`)\n\n{m['briefing']}\n\n")
        out += [f"{i}. {o['prompt']}\n" for i, o in enumerate(m["objectives"], 1)]
    return "".join(out)


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for name, text in (("rules.md", rules_md()), ("console.md", console_md()), ("missions.md", missions_md())):
        path = DOCS / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print(f"Out of date: {', '.join(stale)}. Run: python -m scripts.gen_docs", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
